// Regenerates .env.test.local from the running local Supabase stack's actual
// keys/ports (via `supabase status -o env`), rather than hardcoding them —
// keeps test config correct across CLI/key-generation changes. Run after
// `supabase start` (this is wired into the `db:start` npm script).
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const raw = execFileSync('npx', ['supabase', 'status', '-o', 'env'], { encoding: 'utf8' })

const values = {}
for (const line of raw.split('\n')) {
  const match = line.match(/^([A-Z0-9_]+)="(.*)"$/)
  if (match) values[match[1]] = match[2]
}

if (!values.API_URL || !values.PUBLISHABLE_KEY || !values.SECRET_KEY) {
  console.error('Could not parse Supabase status output — is `supabase start` running?')
  console.error(raw)
  process.exit(1)
}

const contents = `# Generated by scripts/write-test-env.js — do not edit by hand, re-run \`npm run db:start\`.
VITE_SUPABASE_URL=${values.API_URL}
VITE_SUPABASE_ANON_KEY=${values.PUBLISHABLE_KEY}
SUPABASE_SERVICE_ROLE_KEY=${values.SECRET_KEY}
`

writeFileSync('.env.test.local', contents)
console.log('Wrote .env.test.local from local Supabase status.')
